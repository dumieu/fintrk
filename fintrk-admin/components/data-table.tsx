// ─── Helpers ───

function isAutoGenerated(col: Column): boolean {
  if (!col.default) return false;
  return (
    col.default.includes("generated always") ||
    col.default.includes("nextval(")
  );
}

function isLongTextColumn(col: Column): boolean {
  if (col.type === "text" || col.udtName === "text") return true;
  if (col.type === "jsonb" || col.type === "json") return true;
  if (
    col.type === "character varying" &&
    (col.maxLength === null || col.maxLength > 255)
  )
    return true;
  return false;
}

function defaultColWidth(col: Column): number {
  if (col.type === "bytea") return 100;
  if (isLongTextColumn(col)) return 120;
  if (col.type === "boolean" || col.udtName === "bool") return 70;
  if (col.type === "integer" || col.type === "bigint" || col.type === "smallint" || col.udtName === "int4" || col.udtName === "int8" || col.udtName === "int2") return 80;
  if (col.type === "numeric" || col.type === "real" || col.type === "double precision") return 100;
  if (col.type === "timestamp with time zone" || col.type === "timestamp without time zone") return 170;
  if (col.type === "date") return 110;
  if (col.type === "character varying" && col.maxLength !== null) {
    return Math.min(Math.max(col.maxLength * 7 + 24, 70), 200);
  }
  return 130;
}

function isJsonColumn(col: Column): boolean {
  return col.type === "jsonb" || col.type === "json";
}

function tryParseJson(str: string): unknown | null {
  try {
    return JSON.parse(str);
  } catch {
    return null;
  }
}

function rawCellString(value: unknown): string {
  if (value === null || value === undefined) return "";
  if (typeof value === "object") return JSON.stringify(value);
  return String(value);
}

function displayCellValue(value: unknown, col: Column): string {
  if (value === null || value === undefined) return "";
  if (typeof value === "boolean") return value ? "true" : "false";
  if (typeof value === "object") return JSON.stringify(value);
  if (
    col.type === "timestamp with time zone" ||
    col.type === "timestamp without time zone"
  ) {
    try {
      return new Date(String(value)).toLocaleString();
    } catch {
      return String(value);
    }
  }
  return String(value);
}

function JsonValue({ value, depth = 0 }: { value: unknown; depth?: number }) {
  if (value === null) return <span className="text-slate-400 italic">null</span>;
  if (value === undefined) return <span className="text-slate-400 italic">undefined</span>;
  if (typeof value === "boolean") return <span className="text-amber-600 font-medium">{String(value)}</span>;
  if (typeof value === "number") return <span className="text-blue-600 font-medium">{String(value)}</span>;
  if (typeof value === "string") {
    if (value.length > 300) {
      return <span className="text-emerald-700">&quot;{value.slice(0, 300)}…&quot;</span>;
    }
    return <span className="text-emerald-700">&quot;{value}&quot;</span>;
  }

  if (Array.isArray(value)) {
    if (value.length === 0) return <span className="text-slate-500">{"[ ]"}</span>;
    return (
      <span>
        <span className="text-slate-500">{"["}</span>
        <div className="pl-5 border-l border-slate-200 ml-1">
          {value.map((item, i) => (
            <div key={i} className="py-[1px]">
              <JsonValue value={item} depth={depth + 1} />
              {i < value.length - 1 && <span className="text-slate-400">,</span>}
            </div>
          ))}
        </div>
        <span className="text-slate-500">{"]"}</span>
      </span>
    );
  }

  if (typeof value === "object") {
    const entries = Object.entries(value as Record<string, unknown>);
    if (entries.length === 0) return <span className="text-slate-500">{"{}"}</span>;
    return (
      <span>
        <span className="text-slate-500">{"{"}</span>
        <div className="pl-5 border-l border-slate-200 ml-1">
          {entries.map(([k, v], i) => (
            <div key={k} className="py-[1px]">
              <span className="text-violet-600 font-semibold">{k}</span>
              <span className="text-slate-400 mr-1">:</span>
              <JsonValue value={v} depth={depth + 1} />
              {i < entries.length - 1 && <span className="text-slate-400">,</span>}
            </div>
          ))}
        </div>
        <span className="text-slate-500">{"}"}</span>
      </span>
    );
  }

  return <span>{String(value)}</span>;
}

function PrettyJsonViewer({ jsonString }: { jsonString: string }) {
  const parsed = tryParseJson(jsonString);
  if (parsed === null) {
    return (
      <pre className="text-xs leading-5 whitespace-pre-wrap break-words p-3 font-mono text-slate-600">
        {jsonString}
      </pre>
    );
  }
  return (
    <div className="text-[12px] leading-[22px] p-4 font-mono overflow-auto select-text">
      <JsonValue value={parsed} />
    </div>
  );
}

