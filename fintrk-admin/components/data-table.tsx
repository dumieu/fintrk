  function toggleColumnVisibility(colName: string) {
    setHiddenColumns((prev) => {
      const next = new Set(prev);
      if (next.has(colName)) next.delete(colName);
      else next.add(colName);
      return next;
    });
  }

  // ── Multi-cell paste (unified for new + existing rows) ──

  function handlePaste(
    e: React.ClipboardEvent<HTMLInputElement | HTMLTextAreaElement>,
    rowIdx: number,
    colIdx: number
  ) {
    const text = e.clipboardData.getData("text/plain");
    if (!text.includes("\t") && !text.includes("\n")) return;

    e.preventDefault();
    const pasteRows = text
      .replace(/\r\n/g, "\n")
      .split("\n")
      .filter((r) => r.length > 0);

    for (let r = 0; r < pasteRows.length; r++) {
      const pasteCols = pasteRows[r].split("\t");
      const targetRowIdx = rowIdx + r;
      if (targetRowIdx >= combinedRowCount) break;

      let editColOffset = 0;
      for (let c = 0; c < pasteCols.length; c++) {
        let targetColIdx = colIdx + c + editColOffset;
        while (
          targetColIdx < visibleColumns.length &&
          !editableSet.has(visibleColumns[targetColIdx].name)
        ) {
          editColOffset++;
          targetColIdx = colIdx + c + editColOffset;
        }
        if (targetColIdx >= visibleColumns.length) break;
        const targetColName = visibleColumns[targetColIdx].name;

        if (targetRowIdx < newRows.length) {
          handleNewRowCellChange(
            newRows[targetRowIdx].id,
            targetColName,
            pasteCols[c]
          );
        } else {
          const row = rows[targetRowIdx - newRows.length];
          commitCellEdit(row, targetColName, pasteCols[c]);
        }
      }
    }
    toast.success(
      `Pasted ${pasteRows.length} row(s) × ${pasteRows[0]?.split("\t").length || 1} col(s)`
    );
  }

  async function handlePasteAtFocusedCell() {
    if (!focusedCell) return;
    try {
      const text = await navigator.clipboard.readText();
      if (!text.trim()) return;
      const pasteRows = text
        .replace(/\r\n/g, "\n")
        .split("\n")
        .filter((r) => r.length > 0);
      let pasted = 0;
      for (let r = 0; r < pasteRows.length; r++) {
        const pasteCols = pasteRows[r].split("\t");
        const targetRowIdx = focusedCell.rowIdx + r;
        if (targetRowIdx >= combinedRowCount) break;

        let editColOffset = 0;
        for (let c = 0; c < pasteCols.length; c++) {
          let targetColIdx = focusedCell.colIdx + c + editColOffset;
          while (
            targetColIdx < visibleColumns.length &&
            !editableSet.has(visibleColumns[targetColIdx].name)
          ) {
            editColOffset++;
            targetColIdx = focusedCell.colIdx + c + editColOffset;
          }
          if (targetColIdx >= visibleColumns.length) break;
          const targetColName = visibleColumns[targetColIdx].name;

          if (targetRowIdx < newRows.length) {
            handleNewRowCellChange(
              newRows[targetRowIdx].id,
              targetColName,
              pasteCols[c]
            );
          } else {
            const row = rows[targetRowIdx - newRows.length];
            commitCellEdit(row, targetColName, pasteCols[c]);
          }
          pasted++;
        }
      }
      if (pasted > 0)
        toast.success(
          `Pasted ${pasteRows.length} row(s) × ${pasteRows[0]?.split("\t").length || 1} col(s)`
        );
    } catch {
      toast.error("Could not read clipboard");
    }
  }

  // ── Keyboard navigation ──

  function navigateCell(
    direction: "left" | "right" | "up" | "down",
    fromRow: number,
    fromCol: number
  ) {
    let r = fromRow;
    let c = fromCol;

    if (direction === "right") {
      c++;
      while (
        c < visibleColumns.length &&
        !editableSet.has(visibleColumns[c].name)
      )
        c++;
      if (c >= visibleColumns.length) {
        r++;
        c = 0;
        while (
          c < visibleColumns.length &&
          !editableSet.has(visibleColumns[c].name)
        )
          c++;
      }
    } else if (direction === "left") {
      c--;
      while (c >= 0 && !editableSet.has(visibleColumns[c].name)) c--;
      if (c < 0) {
        r--;
        c = visibleColumns.length - 1;
        while (c >= 0 && !editableSet.has(visibleColumns[c].name)) c--;
      }
    } else if (direction === "down") {
      r++;
    } else if (direction === "up") {
      r--;
    }

    if (
      r >= 0 &&
      r < combinedRowCount &&
      c >= 0 &&
      c < visibleColumns.length
    ) {
      setActiveCell(null);
      setFocusedCell({ rowIdx: r, colIdx: c });
      lastCellRef.current = { row: r, col: c };
    } else {
      setActiveCell(null);
      setFocusedCell(null);
    }
  }

  function navigateFocus(
    direction: "left" | "right" | "up" | "down",
    fromRow: number,
    fromCol: number
  ) {
    let r = fromRow;
    let c = fromCol;

    if (direction === "right") {
      c = Math.min(c + 1, visibleColumns.length - 1);
    } else if (direction === "left") {
      c = Math.max(c - 1, 0);
    } else if (direction === "down") {
      r = Math.min(r + 1, combinedRowCount - 1);
    } else if (direction === "up") {
      r = Math.max(r - 1, 0);
    }

    lastCellRef.current = { row: r, col: c };
    setFocusedCell({ rowIdx: r, colIdx: c });
    setActiveCell(null);
    setCellSelection(null);

    const cellEl = document.querySelector(`[data-cell-row="${r}"][data-cell-col="${c}"]`);
    cellEl?.scrollIntoView({ block: "nearest", inline: "nearest" });
  }

  // ── Row selection ──

  function handleRowSelect(
    combinedIdx: number,
    e: React.MouseEvent
  ) {
    setActiveCell(null);
    setFocusedCell(null);
    if (e.shiftKey && lastSelectedRef.current !== null) {
      const from = Math.min(lastSelectedRef.current, combinedIdx);
      const to = Math.max(lastSelectedRef.current, combinedIdx);
      setSelectedRows((prev) => {
        const next = new Set(prev);
        for (let i = from; i <= to; i++) next.add(i);
        return next;
      });
    } else if (e.metaKey || e.ctrlKey) {
      setSelectedRows((prev) => {
        const next = new Set(prev);
        if (next.has(combinedIdx)) next.delete(combinedIdx);
        else next.add(combinedIdx);
        return next;
      });
      lastSelectedRef.current = combinedIdx;
    } else {
      if (selectedRows.has(combinedIdx) && selectedRows.size === 1) {
        setSelectedRows(new Set());
        lastSelectedRef.current = null;
      } else {
        setSelectedRows(new Set([combinedIdx]));
        lastSelectedRef.current = combinedIdx;
      }
    }
  }

  function handleSelectAll() {
    if (selectedRows.size === combinedRowCount) {
      setSelectedRows(new Set());
    } else {
      const all = new Set<number>();
      for (let i = 0; i < combinedRowCount; i++) all.add(i);
      setSelectedRows(all);
    }
  }

  function clearSelection() {
    setSelectedRows(new Set());
    lastSelectedRef.current = null;
  }

  function getRowData(combinedIdx: number): Record<string, string> {
    const data: Record<string, string> = {};
    if (combinedIdx < newRows.length) {
      const nr = newRows[combinedIdx];
      for (const col of visibleColumns) {
        data[col.name] = nr.cells[col.name] ?? "";
      }
    } else {
      const row = rows[combinedIdx - newRows.length];
      for (const col of visibleColumns) {
        if (editedCells[pkOf(row)]?.[col.name] !== undefined) {
          data[col.name] = editedCells[pkOf(row)][col.name];
        } else {
          data[col.name] = rawCellString(row[col.name]);
        }
      }
    }
    return data;
  }

  function handleCopySelectedRows() {
    if (selectedRows.size === 0) return;

    const sortedIndices = Array.from(selectedRows).sort((a, b) => a - b);
    const editableCols = visibleColumns.filter(
      (c) => editableSet.has(c.name)
    );

    const tsvRows = sortedIndices.map((idx) => {
      const data = getRowData(idx);
      return editableCols.map((col) => data[col.name] ?? "").join("\t");
    });

    const tsv = tsvRows.join("\n");
    navigator.clipboard.writeText(tsv);
    toast.success(
      `Copied ${sortedIndices.length} row${sortedIndices.length !== 1 ? "s" : ""}`
    );
  }

  function handleDuplicateSelectedRows() {
    if (selectedRows.size === 0) return;

    const sortedIndices = Array.from(selectedRows).sort((a, b) => a - b);
    const editableCols = visibleColumns.filter(
      (c) => editableSet.has(c.name)
    );

    const created: NewRow[] = sortedIndices.map((idx) => {
      const data = getRowData(idx);
      const cells: Record<string, string> = {};
      for (const col of editableCols) {
        cells[col.name] = data[col.name] ?? "";
      }
      return { id: `__new_${Date.now()}_${idx}`, cells };
    });

    setNewRows((prev) => [...prev, ...created]);
    clearSelection();
    toast.success(
      `Duplicated ${created.length} row${created.length !== 1 ? "s" : ""} as new`
    );
  }

  async function handlePasteAsNewRows() {
    try {
      const text = await navigator.clipboard.readText();
      if (!text.trim()) return;

      const editableCols = visibleColumns.filter(
        (c) => editableSet.has(c.name)
      );

      const pasteRows = text
        .replace(/\r\n/g, "\n")
        .split("\n")
        .filter((r) => r.length > 0);

      const created: NewRow[] = pasteRows.map((line, i) => {
        const vals = line.split("\t");
        const cells: Record<string, string> = {};
        for (let c = 0; c < editableCols.length && c < vals.length; c++) {
          cells[editableCols[c].name] = vals[c];
        }
        return { id: `__new_${Date.now()}_paste_${i}`, cells };
      });

      setNewRows((prev) => [...prev, ...created]);
      clearSelection();
      toast.success(
        `Pasted ${created.length} new row${created.length !== 1 ? "s" : ""}`
      );
    } catch {
      toast.error("Could not read clipboard");
    }
  }

