  // ── Global keyboard shortcuts ──

  useEffect(() => {
    function handleKeyDown(e: KeyboardEvent) {
      const inEditable =
        e.target instanceof HTMLInputElement ||
        e.target instanceof HTMLTextAreaElement ||
        (e.target instanceof HTMLElement && e.target.isContentEditable);
      if (inEditable) return;
      if (!tableRef.current) return;

      // Cell selection shortcuts (take priority over row selection)
      if ((e.metaKey || e.ctrlKey) && e.key === "c" && hasCellSelection) {
        e.preventDefault();
        handleCopyCellSelection();
        return;
      }
      if ((e.metaKey || e.ctrlKey) && e.key === "v" && cellSelection) {
        e.preventDefault();
        handlePasteToCellSelection();
        return;
      }
      if (e.key === "Escape" && cellSelection) {
        setCellSelection(null);
        return;
      }

      // Focused cell shortcuts (Excel-like)
      if (focusedCell && !activeCell) {
        const { rowIdx: fr, colIdx: fc } = focusedCell;

        if (e.key === "ArrowUp" || e.key === "ArrowDown" || e.key === "ArrowLeft" || e.key === "ArrowRight") {
          e.preventDefault();
          const dir = e.key === "ArrowUp" ? "up" : e.key === "ArrowDown" ? "down" : e.key === "ArrowLeft" ? "left" : "right";
          navigateFocus(dir, fr, fc);
          return;
        }
        if (e.key === "Tab") {
          e.preventDefault();
          navigateFocus(e.shiftKey ? "left" : "right", fr, fc);
          return;
        }
        if (e.key === "Enter") {
          e.preventDefault();
          if (editableSet.has(visibleColumns[fc]?.name)) {
            setFocusedCell(null);
            setActiveCell({ rowIdx: fr, colIdx: fc });
          }
          return;
        }
        if (e.key === "Escape") {
          e.preventDefault();
          setFocusedCell(null);
          return;
        }
        if (e.key === "Delete" || e.key === "Backspace") {
          e.preventDefault();
          const colName = visibleColumns[fc]?.name;
          if (colName && editableSet.has(colName)) {
            if (fr < newRows.length) {
              handleNewRowCellChange(newRows[fr].id, colName, "");
            } else {
              const row = rows[fr - newRows.length];
              if (row) commitCellEdit(row, colName, "");
            }
          }
          return;
        }
        if ((e.metaKey || e.ctrlKey) && e.key === "v") {
          e.preventDefault();
          handlePasteAtFocusedCell();
          return;
        }
        if ((e.metaKey || e.ctrlKey) && e.key === "c") {
          e.preventDefault();
          const val = getCellValue(fr, fc);
          navigator.clipboard.writeText(val);
          toast.success("Copied cell");
          return;
        }
        // Typing a printable character → enter edit mode with that character
        if (
          e.key.length === 1 &&
          !e.metaKey &&
          !e.ctrlKey &&
          !e.altKey &&
          editableSet.has(visibleColumns[fc]?.name)
        ) {
          e.preventDefault();
          const colName = visibleColumns[fc]?.name;
          if (colName) {
            if (fr < newRows.length) {
              handleNewRowCellChange(newRows[fr].id, colName, e.key);
            } else {
              const row = rows[fr - newRows.length];
              if (row) commitCellEdit(row, colName, e.key);
            }
            setFocusedCell(null);
            setActiveCell({ rowIdx: fr, colIdx: fc });
          }
          return;
        }
        return;
      }

      // Row selection shortcuts
      if ((e.metaKey || e.ctrlKey) && e.key === "c" && selectedRows.size > 0) {
        e.preventDefault();
        handleCopySelectedRows();
      }

      if (
        (e.metaKey || e.ctrlKey) &&
        e.key === "v" &&
        activeCell === null &&
        selectedRows.size > 0
      ) {
        e.preventDefault();
        handlePasteAsNewRows();
      }

      if (e.key === "Escape" && selectedRows.size > 0) {
        clearSelection();
      }

      if (
        (e.metaKey || e.ctrlKey) &&
        e.key === "a" &&
        selectedRows.size > 0
      ) {
        e.preventDefault();
        handleSelectAll();
      }
    }

    document.addEventListener("keydown", handleKeyDown);
    return () => document.removeEventListener("keydown", handleKeyDown);
  });

  // ── Save / Discard ──

  async function handleSaveAll() {
    if (!pk && newRowCount === 0) return;
    setSaving(true);
    try {
      type SaveOp =
        | { kind: "create"; id: string }
        | { kind: "update"; pkValue: string }
        | { kind: "delete"; pkValue: string };
      const ops: SaveOp[] = [];
      const promises: Promise<Response>[] = [];

      // POST new rows
      for (const newRow of newRows) {
        const data: Record<string, unknown> = {};
        for (const [colName, val] of Object.entries(newRow.cells)) {
          if (editableSet.has(colName) && val !== "") {
            data[colName] = val;
          }
        }
        if (Object.keys(data).length > 0) {
          ops.push({ kind: "create", id: newRow.id });
          promises.push(
            fetch("/api/rows", {
              method: "POST",
              headers: { "Content-Type": "application/json" },
              body: JSON.stringify({ table: tableMeta.name, data }),
            })
          );
        }
      }

      // PUT edited cells - keep PK as text (Number() loses precision on large ids).
      for (const [pkValue, changes] of Object.entries(editedCells)) {
        if (pendingDeletes.has(pkValue)) continue;
        const typedChanges: Record<string, unknown> = {};
        for (const [colName, val] of Object.entries(changes)) {
          typedChanges[colName] = val === "" ? null : val;
        }
        ops.push({ kind: "update", pkValue });
        promises.push(
          fetch("/api/rows", {
            method: "PUT",
            headers: { "Content-Type": "application/json" },
            body: JSON.stringify({
              table: tableMeta.name,
              primaryKey: pk,
              primaryValue: pkValue,
              data: typedChanges,
            }),
          })
        );
      }

      // DELETE marked rows via POST to /api/rows/delete (avoids Next.js DELETE body issues)
      for (const pkValue of pendingDeletes) {
        ops.push({ kind: "delete", pkValue });
        promises.push(
          fetch("/api/rows/delete", {
            method: "POST",
            headers: { "Content-Type": "application/json" },
            body: JSON.stringify({
              table: tableMeta.name,
              primaryKey: pk,
              primaryValue: pkValue,
            }),
          })
        );
      }

      const results = await Promise.all(promises);
      const errors: string[] = [];
      const failedCreateIds = new Set<string>();
      const failedUpdatePks = new Set<string>();
      const failedDeletePks = new Set<string>();

      for (let i = 0; i < results.length; i++) {
        const res = results[i];
        const op = ops[i];
        if (!res || !op) continue;
        if (!res.ok) {
          try {
            const err = await safeJson(res);
            errors.push(String(err.error) || "Unknown error");
          } catch {
            errors.push(`HTTP ${res.status}`);
          }
          if (op.kind === "create") failedCreateIds.add(op.id);
          else if (op.kind === "update") failedUpdatePks.add(op.pkValue);
          else failedDeletePks.add(op.pkValue);
        }
      }

      if (errors.length > 0) {
        // Keep only failed pending work so successful mutations are not re-sent
        // and failed ones remain editable / retryable.
        setNewRows((prev) => prev.filter((r) => failedCreateIds.has(r.id)));
        setEditedCells((prev) => {
          const next: Record<string, Record<string, string>> = {};
          for (const [pkValue, changes] of Object.entries(prev)) {
            if (failedUpdatePks.has(pkValue)) next[pkValue] = changes;
          }
          return next;
        });
        setPendingDeletes(new Set(failedDeletePks));
        toast.error(`${errors.length} failed: ${errors[0]}`);
      } else {
        const parts: string[] = [];
        if (newRowCount > 0) parts.push(`${newRowCount} row(s) created`);
        if (editCount > 0) parts.push(`${editCount} cell(s) updated`);
        if (deleteCount > 0) parts.push(`${deleteCount} row(s) deleted`);
        toast.success(parts.join(", "));
        setNewRows([]);
        setEditedCells({});
        setPendingDeletes(new Set());
        setActiveCell(null);
        setFocusedCell(null);
        clearSelection();
      }

      fetchRows();
    } catch (err) {
      toast.error(err instanceof Error ? err.message : "Save failed");
    } finally {
      setSaving(false);
    }
  }

  function handleDiscardAll() {
    setNewRows([]);
    setEditedCells({});
    setPendingDeletes(new Set());
    setActiveCell(null);
    setFocusedCell(null);
    clearSelection();
  }

