  const [exporting, setExporting] = useState(false);

  async function handleExportExcel() {
    setExporting(true);
    try {
      const params = new URLSearchParams({
        table: tableMeta.name,
        page: "1",
        exportAll: "true",
        sort,
        order,
      });
      if (debouncedSearch) params.set("search", debouncedSearch);
      if (columnFilter && columnValue) {
        params.set("column", columnFilter);
        params.set("value", columnValue);
        if (filterExact) params.set("exact", "true");
      }
      if (columnFiltersJson !== "{}") {
        params.set("filters", columnFiltersJson);
      }

      const res = await fetch(`/api/rows?${params}`);
      const json = await safeJson(res);
      if (json.error) throw new Error(String(json.error));
      const allRows: Record<string, unknown>[] = (json.rows as Record<string, unknown>[]) || [];

      if (allRows.length === 0) {
        toast.error("No rows to export");
        return;
      }

      const headers = visibleColumns.map((c) => c.name);
      const data = allRows.map((row) => {
        const obj: Record<string, unknown> = {};
        for (const h of headers) {
          const val = row[h];
          obj[h] = val === null || val === undefined ? "" : val;
        }
        return obj;
      });

      const ws = XLSX.utils.json_to_sheet(data, { header: headers });
      const wb = XLSX.utils.book_new();
      XLSX.utils.book_append_sheet(wb, ws, tableMeta.name);
      XLSX.writeFile(wb, `${tableMeta.name}_export.xlsx`);
      toast.success(`Exported ${allRows.length} rows to Excel`);
    } catch (err) {
      toast.error(err instanceof Error ? err.message : "Export failed");
    } finally {
      setExporting(false);
    }
  }

